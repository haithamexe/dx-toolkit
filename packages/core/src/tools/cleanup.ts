import { execFile } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { loadConfig, type DxConfig } from "../config.js";
import { scanProjects } from "./projects.js";

/**
 * Finds folders that a build or an install recreates (node_modules, .next, dist, …) in projects
 * you haven't touched for a while, so their disk space can be given back.
 *
 * Safety rules, so nothing that matters is ever offered for deletion:
 * - In a git repo, a folder only counts if git ignores it. A committed `build/` is left alone.
 * - Outside git, only folders that are always regenerated count (node_modules, .next, …), never dist/build.
 * - Symlinks and junctions are never followed, so workspace links can't take their targets with them.
 */
export interface CleanupItem {
  project: string;
  projectDir: string;
  /** Absolute path of the folder. */
  dir: string;
  /** Path inside the project, e.g. "packages/web/node_modules". */
  relative: string;
  bytes: number;
  files: number;
  /** When the project was last active (ms since epoch). */
  lastActive: number;
}

export interface CleanupScan {
  olderThanDays: number;
  /** Biggest first. */
  items: CleanupItem[];
  totalBytes: number;
  /** How many idle projects were looked at. */
  projectsScanned: number;
}

/** Always regenerated by an install or a dev server, so safe even outside git. */
export const ALWAYS_REBUILDABLE = [
  "node_modules",
  ".next",
  ".nuxt",
  ".svelte-kit",
  ".turbo",
  ".parcel-cache",
  ".angular",
  ".expo",
  "__pycache__",
  ".pytest_cache",
];
/** Usually build output, but sometimes committed, so only when git ignores them. */
export const BUILD_OUTPUT = ["dist", "build", "out", "coverage", "target", ".output", ".vercel"];
const SEARCH_DEPTH = 3;

export interface CleanupOptions {
  /** Only projects idle for at least this many days (default 30). */
  days?: number;
  now?: Date;
  config?: DxConfig;
  /** Called as each project is scanned, for a progress line. */
  onProgress?: (done: number, total: number, project: string) => void;
}

export async function findCleanup(options: CleanupOptions = {}): Promise<CleanupScan> {
  const days = Math.max(0, options.days ?? 30);
  const now = (options.now ?? new Date()).getTime();
  const config = options.config ?? loadConfig();
  const cutoff = now - days * 86_400_000;
  const idle = scanProjects(config).filter((p) => p.lastActive && p.lastActive < cutoff);

  const items: CleanupItem[] = [];
  let done = 0;
  for (const project of idle) {
    options.onProgress?.(done, idle.length, project.name);
    const candidates = findCandidates(project.dir);
    const allowed = project.hasGit ? await gitIgnored(project.dir, candidates) : candidates.filter(isAlwaysRebuildable);
    for (const dir of allowed) {
      const { bytes, files } = await folderSize(dir);
      if (bytes === 0 && files === 0) continue;
      items.push({
        project: project.name,
        projectDir: project.dir,
        dir,
        relative: path.relative(project.dir, dir).split(path.sep).join("/"),
        bytes,
        files,
        lastActive: project.lastActive,
      });
    }
    done++;
  }
  options.onProgress?.(done, idle.length, "");
  items.sort((a, b) => b.bytes - a.bytes);
  return { olderThanDays: days, items, totalBytes: items.reduce((n, i) => n + i.bytes, 0), projectsScanned: idle.length };
}

/** Folders with a known build/install name, up to a few levels down (monorepo packages), not inside each other. */
export function findCandidates(projectDir: string): string[] {
  const names = new Set([...ALWAYS_REBUILDABLE, ...BUILD_OUTPUT]);
  const found: string[] = [];
  const walk = (dir: string, depth: number) => {
    let entries: fs.Dirent[];
    try {
      entries = fs.readdirSync(dir, { withFileTypes: true });
    } catch {
      return;
    }
    for (const e of entries) {
      if (!e.isDirectory()) continue; // symlinks and junctions are not directories here
      const full = path.join(dir, e.name);
      if (names.has(e.name)) {
        found.push(full);
        continue;
      }
      if (e.name.startsWith(".") || depth >= SEARCH_DEPTH) continue;
      walk(full, depth + 1);
    }
  };
  walk(projectDir, 1);
  return found;
}

function isAlwaysRebuildable(dir: string): boolean {
  return ALWAYS_REBUILDABLE.includes(path.basename(dir));
}

/** The subset of `dirs` that git ignores in this repo. If git can't answer, nothing is returned. */
async function gitIgnored(repo: string, dirs: string[]): Promise<string[]> {
  if (dirs.length === 0) return [];
  const rel = dirs.map((d) => path.relative(repo, d).split(path.sep).join("/") + "/");
  try {
    const stdout = await new Promise<string>((resolve, reject) => {
      const child = execFile("git", ["-C", repo, "check-ignore", "--stdin"], { windowsHide: true }, (err, out) => {
        // Exit code 1 means "none of them are ignored", which is an answer, not a failure.
        if (err && (err as { code?: unknown }).code !== 1) reject(err);
        else resolve(out ?? "");
      });
      child.stdin?.end(rel.join("\n") + "\n");
    });
    const ignored = new Set(stdout.split(/\r?\n/).map((l) => l.trim().replace(/\/$/, "")).filter(Boolean));
    return dirs.filter((_, i) => ignored.has(rel[i].replace(/\/$/, "")));
  } catch {
    return [];
  }
}

/** Total size of every file below `dir`, without following symlinks or junctions. */
export async function folderSize(dir: string): Promise<{ bytes: number; files: number }> {
  let bytes = 0;
  let files = 0;
  const queue = [dir];
  while (queue.length) {
    const batch = queue.splice(0, 64);
    await Promise.all(
      batch.map(async (d) => {
        let entries: fs.Dirent[];
        try {
          entries = await fs.promises.readdir(d, { withFileTypes: true });
        } catch {
          return;
        }
        const stats: Promise<void>[] = [];
        for (const e of entries) {
          const full = path.join(d, e.name);
          if (e.isDirectory()) queue.push(full);
          else if (e.isFile()) {
            stats.push(
              fs.promises.lstat(full).then(
                (s) => {
                  bytes += s.size;
                  files++;
                },
                () => undefined,
              ),
            );
          }
        }
        await Promise.all(stats);
      }),
    );
  }
  return { bytes, files };
}

export interface DeleteResult {
  dir: string;
  ok: boolean;
  bytes: number;
  message: string;
}

/** Deletes the folders. Each one is checked again first, so a stale list can't delete the wrong thing. */
export async function deleteCleanup(items: CleanupItem[]): Promise<DeleteResult[]> {
  const known = new Set([...ALWAYS_REBUILDABLE, ...BUILD_OUTPUT]);
  const results: DeleteResult[] = [];
  for (const item of items) {
    const inside = path.relative(item.projectDir, item.dir);
    if (!known.has(path.basename(item.dir)) || !inside || inside.startsWith("..") || path.isAbsolute(inside)) {
      results.push({ dir: item.dir, ok: false, bytes: 0, message: "not a build folder inside its project; left alone" });
      continue;
    }
    try {
      await fs.promises.rm(item.dir, { recursive: true, force: true, maxRetries: 3 });
      results.push({ dir: item.dir, ok: true, bytes: item.bytes, message: "deleted" });
    } catch (err) {
      results.push({ dir: item.dir, ok: false, bytes: 0, message: (err as Error).message });
    }
  }
  return results;
}

/** 1536 → "1.5 KB" */
export function formatBytes(bytes: number): string {
  const units = ["B", "KB", "MB", "GB", "TB"];
  let n = bytes;
  let i = 0;
  while (n >= 1024 && i < units.length - 1) {
    n /= 1024;
    i++;
  }
  return `${i === 0 ? n : n.toFixed(n >= 100 ? 0 : 1)} ${units[i]}`;
}

